import { writeFile } from "node:fs/promises";

const provinceCodes = [
  "130000", "140000", "150000", "210000", "220000", "230000",
  "320000", "330000", "340000", "350000", "360000", "370000",
  "410000", "420000", "430000", "440000", "450000", "460000",
  "510000", "520000", "530000", "540000", "610000", "620000",
  "630000", "640000", "650000",
];
const directRegions = {
  110000: [["110000", "北京市", 116.4074, 39.9042]],
  120000: [["120000", "天津市", 117.2008, 39.0842]],
  310000: [["310000", "上海市", 121.4737, 31.2304]],
  500000: [["500000", "重庆市", 106.5516, 29.563]],
  710000: [["710000", "台湾省", 121.5654, 25.033]],
  810000: [["810000", "香港特别行政区", 114.1694, 22.3193]],
  820000: [["820000", "澳门特别行政区", 113.5439, 22.1987]],
};

const result = { ...directRegions };
for (const provinceCode of provinceCodes) {
  const endpoint = `https://geo.datav.aliyun.com/areas_v3/bound/${provinceCode}_full.json`;
  const response = await fetch(endpoint);
  if (!response.ok) throw new Error(`${provinceCode}: ${response.status}`);
  const body = await response.json();
  result[provinceCode] = (body.features || [])
    .map(({ properties = {} }) => [
      String(properties.adcode || ""),
      String(properties.name || ""),
      Number(properties.center?.[0]),
      Number(properties.center?.[1]),
    ])
    .filter(([code, name, lng, lat]) =>
      /^\d{6}$/.test(code) && name && Number.isFinite(lng) && Number.isFinite(lat)
    )
    .sort(([left], [right]) => left.localeCompare(right));
}

const banner = `// Generated by scripts/build-city-data.mjs.
// Administrative names/codes: public Ministry of Civil Affairs / NBS-derived division data.
// Centers: Alibaba Cloud DataV administrative GeoJSON. Bundled locally to avoid runtime lookup failures.
`;
await writeFile(
  new URL("../city-data.js", import.meta.url),
  `${banner}window.TRAVEL_ROLLS_CITY_DATA = Object.freeze(${JSON.stringify(result, null, 2)});\n`,
  "utf8"
);
console.log(`Generated ${Object.values(result).reduce((sum, cities) => sum + cities.length, 0)} city-level entries.`);
